--  Ejecutá este script en Supabase → SQL Editor.
-- ============================================================

create table if not exists public.clases_auditoria (
  id bigint generated by default as identity primary key,
  creado_en timestamptz not null default now(),
  fecha date not null,
  pestana text not null,
  fila integer,
  carrera text,
  semestre text,
  asignatura text,
  seccion text,
  tipo text,
  docente text,
  hora_inicio text,
  hora_fin text,
  aula text,
  estado text,
  observacion text,
  reemplazante text
);

comment on table public.clases_auditoria is
  'Historial de cada clase cargada desde el formulario web.';

-- La tabla queda cerrada al público: solo la service role key
-- (usada por el servidor) puede leer y escribir.
alter table public.clases_auditoria enable row level security;

create index if not exists clases_auditoria_fecha_idx
  on public.clases_auditoria (fecha desc);

create index if not exists clases_auditoria_pestana_idx
  on public.clases_auditoria (pestana);
